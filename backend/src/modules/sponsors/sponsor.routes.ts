import { Router } from "express";
import { authenticate } from "../../middlewares/authenticate.middleware.js";
import { optionalAuthenticate } from "../../middlewares/optionalAuthenticate.middleware.js";
import { requireAdmin } from "../../middlewares/authorizeAdmin.middleware.js";
import { validate } from "../../middlewares/validate.middleware.js";
import { controllers } from "../../container/index.js";
import { sponsorCreateSchema,sponsorUpdateSchema } from "./sponsor.dto.js";
export const sponsorRouter=Router();
sponsorRouter.get("/",optionalAuthenticate,controllers.sponsors.list);
sponsorRouter.get("/:id",optionalAuthenticate,controllers.sponsors.get);
sponsorRouter.post("/",authenticate,requireAdmin,validate(sponsorCreateSchema),controllers.sponsors.create);
sponsorRouter.patch("/:id",authenticate,requireAdmin,validate(sponsorUpdateSchema),controllers.sponsors.update);
sponsorRouter.delete("/:id",authenticate,requireAdmin,controllers.sponsors.remove);
